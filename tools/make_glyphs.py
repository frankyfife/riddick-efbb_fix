# Generates the extra controller glyphs (own artwork) as RGBA arrays for the DLL.
# A/B/X/Y are taken at runtime from the game's own GUI.xtc (original Xbox art).
import os, sys, math
from PIL import Image, ImageDraw, ImageFont, ImageFilter
OUT = sys.argv[1]
S = 4                     # supersampling
H = 32                    # final glyph height
BOLD = r"C:\Windows\Fonts\arialbd.ttf"

def gem(w, h, base, shape="ellipse"):
    W, Hh = w * S, h * S
    im = Image.new("RGBA", (W, Hh), (0, 0, 0, 0))
    mask = Image.new("L", (W, Hh), 0)
    md = ImageDraw.Draw(mask)
    m = 2 * S
    if shape == "ellipse":
        md.ellipse((m, m, W - m, Hh - m), fill=255)
    elif shape == "pill":
        md.rounded_rectangle((m, m, W - m, Hh - m), radius=(Hh - 2 * m) // 2, fill=255)
    elif shape == "trigger":
        md.rounded_rectangle((m, m, W - m, Hh - m), radius=(W - 2 * m) // 2, fill=255)
        md.rounded_rectangle((m, Hh // 3, W - m, Hh - m), radius=3 * S, fill=255)
    # radial shading like the original gems (light from top-left)
    px = im.load()
    cx, cy = W * 0.38, Hh * 0.30
    R = math.hypot(W, Hh) * 0.62
    for y in range(Hh):
        for x in range(W):
            t = min(1.0, math.hypot(x - cx, y - cy) / R)
            k = 1.45 - 0.95 * t
            px[x, y] = tuple(max(0, min(255, int(c * k))) for c in base) + (255,)
    # dark rim from the mask outline
    er = mask.filter(ImageFilter.MinFilter(int(1.6 * S) * 2 + 1))
    edge = Image.eval(Image.merge("L", [mask]), lambda v: v)
    rimA = Image.frombytes("L", mask.size, bytes(max(0, a - b) for a, b in zip(mask.tobytes(), er.tobytes())))
    rim = Image.new("RGBA", (W, Hh), (20, 20, 22, 255)); rim.putalpha(rimA)
    im = Image.alpha_composite(im, rim)
    im.putalpha(mask)
    return im

def label(im, text, size, color=(245, 245, 245), dy=0):
    W, Hh = im.size
    d = ImageDraw.Draw(im)
    f = ImageFont.truetype(BOLD, int(size * S))
    bb = d.textbbox((0, 0), text, font=f)
    x = (W - (bb[2] - bb[0])) / 2 - bb[0]
    y = (Hh - (bb[3] - bb[1])) / 2 - bb[1] + dy * S
    d.text((x + S * 0.8, y + S * 0.8), text, font=f, fill=(0, 0, 0, 170))
    d.text((x, y), text, font=f, fill=color + (255,))
    return im

def arrow(im, direction):
    W, Hh = im.size
    d = ImageDraw.Draw(im)
    cx, cy, r = W / 2, Hh / 2, Hh * 0.22
    if direction == "left":
        pts = [(cx - r, cy), (cx + r * 0.8, cy - r), (cx + r * 0.8, cy + r)]
    else:
        pts = [(cx + r, cy), (cx - r * 0.8, cy - r), (cx - r * 0.8, cy + r)]
    d.polygon(pts, fill=(245, 245, 245, 255))
    return im

def dpad(hi=None):
    W = Hh = H * S
    im = Image.new("RGBA", (W, Hh), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    a = W * 0.34; m = 2 * S
    body = (88, 90, 96, 255); edge = (20, 20, 22, 255); lit = (235, 235, 235, 255)
    d.rounded_rectangle(((W - a) / 2, m, (W + a) / 2, Hh - m), radius=3 * S, fill=body, outline=edge, width=int(1.6 * S))
    d.rounded_rectangle((m, (Hh - a) / 2, W - m, (Hh + a) / 2), radius=3 * S, fill=body, outline=edge, width=int(1.6 * S))
    d.rectangle(((W - a) / 2 + 1.6 * S, (Hh - a) / 2 + 1.6 * S, (W + a) / 2 - 1.6 * S, (Hh + a) / 2 - 1.6 * S), fill=body)
    c = W / 2; t = a * 0.32
    arms = {"up": [(c, m + 3 * S), (c - t, m + 3 * S + t * 1.4), (c + t, m + 3 * S + t * 1.4)],
            "down": [(c, Hh - m - 3 * S), (c - t, Hh - m - 3 * S - t * 1.4), (c + t, Hh - m - 3 * S - t * 1.4)],
            "left": [(m + 3 * S, c), (m + 3 * S + t * 1.4, c - t), (m + 3 * S + t * 1.4, c + t)],
            "right": [(W - m - 3 * S, c), (W - m - 3 * S - t * 1.4, c - t), (W - m - 3 * S - t * 1.4, c + t)]}
    for k, p in arms.items():
        d.polygon(p, fill=lit if (hi is None or hi == k) else (150, 150, 155, 255))
    return im

GREY = (96, 98, 106)
glyphs = {
    "LB": label(gem(46, H, GREY, "pill"), "LB", 15),
    "RB": label(gem(46, H, GREY, "pill"), "RB", 15),
    "LT": label(gem(30, H, GREY, "trigger"), "LT", 13, dy=1.5),
    "RT": label(gem(30, H, GREY, "trigger"), "RT", 13, dy=1.5),
    "BACK": arrow(gem(H, H, (60, 62, 68)), "left"),
    "START": arrow(gem(H, H, (60, 62, 68)), "right"),
    "LS": label(gem(H, H, GREY), "LS", 13),
    "RS": label(gem(H, H, GREY), "RS", 13),
    "DPAD": dpad(), "DPAD_UP": dpad("up"), "DPAD_DOWN": dpad("down"),
    "DPAD_LEFT": dpad("left"), "DPAD_RIGHT": dpad("right"),
}
lines = ["// generated by tools/make_glyphs.py - own artwork", "#pragma once", "#include <stdint.h>",
         "struct GlyphArt { const char* name; int w, h; const uint8_t* rgba; };"]
sheet = Image.new("RGBA", (60 * len(glyphs), 40), (60, 60, 60, 255))
for i, (name, im) in enumerate(glyphs.items()):
    im = im.resize((max(4, im.width // S), im.height // S), Image.LANCZOS)
    sheet.paste(im, (i * 60 + 4, 4), im)
    data = im.tobytes()
    lines.append("static const uint8_t g_art_%s[] = {%s};" % (name, ",".join(str(b) for b in data)))
lines.append("static const GlyphArt g_glyphArt[] = {")
for name, im in glyphs.items():
    lines.append('  { "%s", %d, %d, g_art_%s },' % (name, max(4, im.width // S), im.height // S, name))
lines.append("};")
open(OUT, "w").write("\n".join(lines) + "\n")
sheet.save(os.path.join(os.path.dirname(OUT), "..", "art", "glyph_sheet.png"))
print("ok", len(glyphs))
